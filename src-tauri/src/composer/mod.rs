use write::{PlanItem, Written};

pub struct Composer {
    data_dir: PathBuf,
    written: Mutex<Vec<Written>>,
}

impl Composer {
    pub fn manage(app: &AppHandle) -> tauri::Result<()> {
        let data_dir = app.path().app_data_dir()?;
        let written = read_records(&data_dir.join("composed.json"));
        app.manage(Composer {
            data_dir,
            written: Mutex::new(written),
        });
        Ok(())
    }

    fn docs_dir(&self) -> PathBuf {
        docs_dir(&self.data_dir)
    }

    /// Third-party blocks fetched by "최신 받아오기".
    fn cache_dir(&self) -> PathBuf {
        self.data_dir.join("catalog-cache")
    }

    fn doc_path(&self, id: &str) -> ops::Result<PathBuf> {
        check_doc_id(id)?;
        Ok(self.docs_dir().join(format!("{id}.json")))
    }
}

/// Where documents are saved (also what sync reads and writes).
pub fn docs_dir(data_dir: &Path) -> PathBuf {
    data_dir.join("compositions")
}

/// A file that exists but does not parse is moved aside, so the next save
/// does not silently drop what it held.
fn read_records(path: &Path) -> Vec<Written> {
    let Ok(bytes) = fs::read(path) else {
        return Vec::new();
    };
    serde_json::from_slice(&bytes).unwrap_or_else(|_| {
        let _ = fs::rename(path, path.with_extension("json.corrupt"));
        Vec::new()
    })
}

/// Document ids are generated by the app: short lowercase ASCII.
fn check_doc_id(id: &str) -> ops::Result<()> {
    let ok = !id.is_empty()
        && id.len() <= 64
        && id
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
    if ok {
        Ok(())
    } else {
        Err(crate::tr!(
            "잘못된 문서 id: {id}",
            "Invalid document id: {id}"
        ))
    }
}

#[derive(Clone, Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct DocMeta {
    pub id: String,
    pub name: String,
    pub updated_at: f64,
}

pub(crate) fn list_docs(dir: &Path) -> Vec<DocMeta> {
    let mut docs: Vec<DocMeta> = fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|entry| {
            let path = entry.path();
            let id = path.file_stem()?.to_str()?.to_string();
            if path.extension()? != "json" || check_doc_id(&id).is_err() {
                return None;
            }
            let value: Value = serde_json::from_slice(&fs::read(&path).ok()?).ok()?;
            Some(DocMeta {
                name: value["name"]
                    .as_str()
                    .map(str::to_string)
                    .unwrap_or_else(|| crate::tr!("제목 없음", "Untitled")),
                updated_at: value["updatedAt"].as_f64().unwrap_or(0.0),
                id,
            })
        })
        .collect();
    docs.sort_by(|a, b| b.updated_at.total_cmp(&a.updated_at));
    docs
}

/// Tells the windows that documents were added outside them (`docIds`).
pub const DOCS_EVENT: &str = "composer-docs-changed";

/// Saves a new document made outside the app (the MCP server, through the
/// bridge). An existing document is never replaced.
pub fn save_new_doc(app: &AppHandle, doc: Value) -> ops::Result<String> {
    let id = doc["id"]
        .as_str()
        .ok_or_else(|| crate::tr!("문서 id가 없어요", "The document has no id"))?
        .to_string();
    parse_doc(doc.clone())?;
    let path = app.state::<Composer>().doc_path(&id)?;
    if path.exists() {
        return Err(crate::tr!(
            "이미 있는 문서예요: {id}",
            "The document already exists: {id}"
        ));
    }
    let text = serde_json::to_string(&doc).map_err(|e| e.to_string())?;
    ops::write_atomic(&path, text)?;
    crate::sync::changed(app);
    let _ = app.emit(DOCS_EVENT, vec![id.clone()]);
    Ok(id)
}

/// Document ids are checked the same way inside and outside the app.
pub fn valid_doc_id(id: &str) -> bool {
    check_doc_id(id).is_ok()
}

fn catalog_for(app: &AppHandle) -> Vec<Block> {
    let cache = app.state::<Composer>().cache_dir();
    catalog::all(&app.state::<Library>().items(), Some(&cache))
}

pub(crate) fn parse_doc(doc: Value) -> ops::Result<Doc> {
    serde_json::from_value(doc).map_err(|e| {
        crate::tr!(
            "문서를 읽지 못했어요: {e}",
            "Couldn't read the document: {e}"
        )
    })
}

/// The project folder, resolved so records match however the path was typed.
fn project_root(project: &str) -> ops::Result<(PathBuf, String)> {
    let root = fs::canonicalize(project).map_err(|e| {
        crate::tr!(
            "프로젝트 폴더를 열 수 없어요: {e}",
            "Couldn't open the project folder: {e}"
        )
    })?;
    if !root.is_dir() {
        return Err(crate::tr!(
            "프로젝트 폴더가 아니에요",
            "Not a project folder"
        ));
    }
    let key = root.display().to_string();
    Ok((root, key))
}

async fn blocking<T: Send + 'static>(
    app: AppHandle,
    f: impl FnOnce(&AppHandle) -> ops::Result<T> + Send + 'static,
) -> ops::Result<T> {
    tauri::async_runtime::spawn_blocking(move || f(&app))
        .await
        .map_err(|e| e.to_string())?
}

#[tauri::command]
pub async fn composer_catalog(app: AppHandle) -> Result<Vec<Block>, String> {
    blocking(app, |app| Ok(catalog_for(app))).await
}

#[tauri::command]
pub async fn composer_refresh_external(app: AppHandle) -> Result<refresh::RefreshResult, String> {
    blocking(app, |app| {
        Ok(refresh::refresh(&app.state::<Composer>().cache_dir()))
    })
    .await
}

#[tauri::command]
pub async fn composer_docs(app: AppHandle) -> Result<Vec<DocMeta>, String> {
    blocking(app, |app| {
        Ok(list_docs(&app.state::<Composer>().docs_dir()))
    })
    .await
}

#[tauri::command]
pub async fn composer_doc_load(app: AppHandle, id: String) -> Result<Value, String> {
    blocking(app, move |app| {
        let path = app.state::<Composer>().doc_path(&id)?;
        let bytes = fs::read(&path).map_err(|e| {
            crate::tr!(
                "문서를 열 수 없어요: {e}",
                "Couldn't open the document: {e}"
            )
        })?;
        serde_json::from_slice(&bytes)
            .map_err(|e| crate::tr!("문서가 손상됐어요: {e}", "The document is corrupted: {e}"))
    })
    .await
}

#[tauri::command]
pub async fn composer_doc_save(app: AppHandle, doc: Value) -> Result<(), String> {
    blocking(app, move |app| {
        let id = doc["id"]
            .as_str()
            .ok_or_else(|| crate::tr!("문서 id가 없어요", "The document has no id"))?;
        let path = app.state::<Composer>().doc_path(id)?;
        let text = serde_json::to_string(&doc).map_err(|e| e.to_string())?;
        ops::write_atomic(&path, text)?;
        crate::sync::changed(app);
        Ok(())
    })
    .await
}

#[tauri::command]
pub async fn composer_doc_delete(app: AppHandle, id: String) -> Result<(), String> {
    blocking(app, move |app| {
        let path = app.state::<Composer>().doc_path(&id)?;
        match fs::remove_file(&path) {
            Ok(()) => {
                crate::sync::changed(app);
                Ok(())
            }
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(crate::tr!(
                "문서를 지우지 못했어요: {e}",
                "Couldn't delete the document: {e}"
            )),
        }
    })
    .await
}

#[tauri::command]
pub async fn composer_compile(
    app: AppHandle,
    doc: Value,
    tool: ToolId,
) -> Result<Compiled, String> {
    blocking(app, move |app| {
        let doc = parse_doc(doc)?;
        Ok(compile::compile(&doc, &catalog_for(app), tool))
    })
    .await
}

#[tauri::command]
pub async fn composer_plan(
    app: AppHandle,
    project: String,
    doc: Value,
    tool: ToolId,
) -> Result<Vec<PlanItem>, String> {
    blocking(app, move |app| {
        let (root, key) = project_root(&project)?;
        let compiled = compile::compile(&parse_doc(doc)?, &catalog_for(app), tool);
        let composer = app.state::<Composer>();
        let records = composer.written.lock().unwrap_or_else(|e| e.into_inner());
        Ok(compiled
            .files
            .iter()
            .map(|f| write::plan_file(&root, &key, f, &records, tool))
            .collect())
    })
    .await
}

#[derive(Debug, Default, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct WriteResult {
    pub written: Vec<String>,
    /// Paths not written: unconfirmed, blocked, or failed (with the reason).
    pub skipped: Vec<(String, String)>,
    /// Written (or unchanged) paths whose git exclude could not be updated.
    pub warnings: Vec<(String, String)>,
}

/// Permission to overwrite one file, valid only while it still has the
/// content the user saw in the preview.
#[derive(Debug, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Confirmation {
    pub path: String,
    pub old_hash: Option<String>,
}

/// Recompiles and re-plans before writing, so a file changed since the
/// preview is never overwritten without a fresh confirmation.
#[tauri::command]
pub async fn composer_write(
    app: AppHandle,
    project: String,
    doc: Value,
    tool: ToolId,
    confirmed: Vec<Confirmation>,
) -> Result<WriteResult, String> {
    blocking(app, move |app| {
        let (root, key) = project_root(&project)?;
        let compiled = compile::compile(&parse_doc(doc)?, &catalog_for(app), tool);
        let composer = app.state::<Composer>();
        let mut records = composer.written.lock().unwrap_or_else(|e| e.into_inner());
        let mut result = WriteResult::default();

        for file in &compiled.files {
            let item = write::plan_file(&root, &key, file, &records, tool);
            let approved = confirmed
                .iter()
                .any(|c| c.path == file.path && c.old_hash == item.old_hash);
            let skip = match &item.status {
                write::Status::Unchanged => None,
                write::Status::Blocked(reason) => Some(reason.clone()),
                s if s.needs_confirm() && !approved => Some(crate::tr!(
                    "확인하지 않았거나 확인한 뒤에 파일이 바뀌어서 건너뛰었어요",
                    "Skipped: not confirmed, or the file changed after you confirmed"
                )),
                _ => None,
            };
            if let Some(reason) = skip {
                result.skipped.push((file.path.clone(), reason));
                continue;
            }
            if item.status != write::Status::Unchanged {
                match write::write_file(&root, &key, file, &item) {
                    Ok(record) => {
                        records.retain(|r| !(r.project == record.project && r.path == record.path));
                        records.push(record);
                        result.written.push(file.path.clone());
                    }
                    Err(reason) => {
                        result.skipped.push((file.path.clone(), reason));
                        continue;
                    }
                }
            }
            // Also for unchanged files: the scope may have flipped.
            if let Err(reason) = write::sync_exclude(&root, file) {
                result.warnings.push((file.path.clone(), reason));
            }
        }

        let text = serde_json::to_string_pretty(&*records).map_err(|e| e.to_string())?;
        ops::write_atomic(&composer.data_dir.join("composed.json"), text)?;
        Ok(result)
    })
    .await
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn doc_ids_are_restricted() {
        assert!(check_doc_id("doc-lx2k9").is_ok());
        for bad in ["", "../x", "A", "a/b", "a.json", &"x".repeat(65)] {
            assert!(check_doc_id(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn lists_docs_newest_first() {
        let tmp = tempfile::tempdir().unwrap();
        fs::write(
            tmp.path().join("a.json"),
            r#"{"id":"a","name":"A","updatedAt":1}"#,
        )
        .unwrap();
        fs::write(
            tmp.path().join("b.json"),
            r#"{"id":"b","name":"B","updatedAt":2}"#,
        )
        .unwrap();
        fs::write(tmp.path().join("bad.json"), "not json").unwrap();
        fs::write(tmp.path().join("Upper.json"), "{}").unwrap();
        let docs = list_docs(tmp.path());
        let names: Vec<_> = docs.iter().map(|d| d.name.as_str()).collect();
        assert_eq!(names, ["B", "A"]);
    }
}
